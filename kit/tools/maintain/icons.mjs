#!/usr/bin/env node
// Prepare the local reference from the same registry and official package as web docs.
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../../../', import.meta.url));
const registry=await readFile(path.join(root,'kit/web/src/icons/index.tsx'),'utf8');
const block=registry.match(/export const icons = \{([\s\S]*?)\n\}/);
if(!block)throw new Error('Missing docs icon registry.');
const pkg=path.join(root,'kit/web/node_modules/lucide-react'),version=JSON.parse(await readFile(path.join(pkg,'package.json'),'utf8')).version;
const exports=await readFile(path.join(pkg,'dist/esm/lucide-react.mjs'),'utf8'),files=new Map();
for(const m of exports.matchAll(/export \{([^}]*)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g))for(const n of m[1].matchAll(/default as ([A-Za-z0-9]+)/g))files.set(n[1],m[2]);
const icons=[];
for(const m of block[1].matchAll(/'([a-z0-9-]+)\/([a-z0-9-]+)':\s*([A-Za-z0-9]+)/g)){
 const file=files.get(m[3]);if(!file)throw new Error('Not a Lucide export: '+m[3]);
 const {__iconData}=await import(pathToFileURL(path.join(pkg,'dist/esm/icons',file+'.mjs')));
 icons.push({name:m[1]+'/'+m[2],component:m[3],nodes:__iconData.node.map(([tag,attrs])=>[tag,Object.fromEntries(Object.entries(attrs).filter(([key])=>key!=='key'))])});
}
const out=path.join(root,'kit/manager/client/assets/icons');await mkdir(out,{recursive:true});
await writeFile(path.join(out,'catalog.mjs'),'// Generated by kit/tools/maintain/icons.mjs from official lucide-react and the docs registry.\nexport const iconLibrary = '+JSON.stringify({name:'Lucide',version,license:'ISC',registryHash:createHash('sha256').update(block[1]).digest('hex')})+';\nexport const libraryIcons = '+JSON.stringify(icons)+';\n');
await copyFile(path.join(pkg,'LICENSE'),path.join(out,'LUCIDE-LICENSE.txt'));
console.log(`Prepared ${icons.length} official Lucide ${version} icons.`);

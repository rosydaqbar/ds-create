// Writes src/components/index.ts: one export line per component file, in level order.
// Run after adding a component (npm run index); `npm run build` runs it too.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/components');
const lines = ['// GENERATED by scripts/build-index.mjs — do not edit.'];
for (const level of ['assets', 'parts', 'components', 'sections']) {
  const files = readdirSync(join(dir, level)).filter((f) => f.endsWith('.tsx') && !f.startsWith('_')).sort();
  for (const f of files) lines.push(`export * from './${level}/${f.replace(/\.tsx$/, '')}';`);
}
lines.push("export { Icon, icons, iconNames, type IconName } from '../icons';");
writeFileSync(join(dir, 'index.ts'), lines.join('\n') + '\n');
console.log(`components index: ${lines.length - 2} modules`);
